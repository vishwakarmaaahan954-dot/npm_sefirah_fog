/**
 * Deeply merges user overrides on top of a base preset (defaults to 'grayFog').
 */
export function resolveConfig(options: SefirahFogOptions = {}): SefirahFogConfig {
  const baseName: FogPresetName = options.preset ?? 'grayFog';
  const base = FOG_PRESETS[baseName] ?? FOG_PRESETS.grayFog;

  return {
    preset: baseName,
    opacity: options.opacity ?? base.opacity,
    scale: options.scale ?? base.scale,
    thickness: options.thickness ?? base.thickness,
    detail: options.detail ?? base.detail,
    backgroundColor: options.backgroundColor ?? base.backgroundColor,
    transparentBackground:
      options.transparentBackground ?? base.transparentBackground,
    maxDpr: options.maxDpr ?? base.maxDpr,
    wakeResolution: options.wakeResolution ?? base.wakeResolution,
    powerPreference: options.powerPreference ?? base.powerPreference,
    resolutionScale: options.resolutionScale ?? base.resolutionScale,
    targetFps: options.targetFps ?? base.targetFps,
    pauseWhenOffscreen: options.pauseWhenOffscreen ?? base.pauseWhenOffscreen,
    respectReducedMotion:
      options.respectReducedMotion ?? base.respectReducedMotion,
    opaqueCanvas: options.opaqueCanvas ?? base.opaqueCanvas,
    alertOnError: options.alertOnError ?? base.alertOnError,
    onError: options.onError ?? base.onError,
    layers: options.layers
      ? options.layers.map((layer) => ({ ...layer }))
      : base.layers.map((layer) => ({ ...layer })),
    animation: mergeDefined(base.animation, options.animation),
    interaction: mergeDefined(base.interaction, options.interaction),
    backlight: {
      ...mergeDefined(base.backlight, options.backlight),
      position: mergeDefined(
        base.backlight.position,
        options.backlight?.position
      ),
    },
    stars: mergeDefined(base.stars, options.stars),
  };
}
